# L/RRY phase 4.3a: the constant tables of firmware/src/lrry_tab.h (coefficient maths without libm on the device).
# Run: python3 tools/gen_lrry_tables.py > firmware/src/lrry_tab_data.h   (the output is committed; this script is the source of it)
import math

FS = 8388608          # Q23 full scale
SR = 44100.0
Q28 = 1 << 28

def rnd(x):
    return int(round(x))   # round half to even, as lrint

def arr(name, ctype, vals, per=8):
    out = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)

print("/* generated by tools/gen_lrry_tables.py: do not edit. L/RRY coefficient tables (see lrry_tab.h for what each is and its error). */")
print("#pragma once")
print("#include <stdint.h>")

# 1. tan(pi fc / SR), Q28, fc = 30 Hz * (16000/30)^(pos / 32512), pos = j * 64 (Q8 position in DUELL's 0..127 cutoff table: SVF_G's axis, voice.c idx = 40 + (uc * 99 >> 6))
tan_t = []
for j in range(512):
    fc = 30.0 * (16000.0 / 30.0) ** (j * 64 / 32512.0)
    tan_t.append(rnd(math.tan(math.pi * fc / SR) * Q28))
print(arr("LT_TAN", "uint32_t", tan_t))

# 2. damping k = 1/q for RES 0..127: 2.0 (q 0.5) down to 0.05 (q 20), exponential, Q28
k_t = [rnd(2.0 * (0.025 ** (r / 127.0)) * Q28) for r in range(128)]
print(arr("LT_KRES", "uint32_t", k_t))

# 3. pan gain of the left channel for pan = -1 + i / 128 (i 0..256): sqrt2 cos((pan + 1) pi / 4), Q28; the right is the table read backwards
pan_t = []
for i in range(257):
    pan = -1.0 + i / 128.0
    pan_t.append(rnd(math.sqrt(2.0) * math.cos((pan + 1.0) * math.pi / 4.0) * Q28))
print(arr("LT_PANG", "int32_t", pan_t))

# 4. sine, quarter wave: sin(2 pi i / 4096) * (FS - 1), i 0..1024
sin_t = [rnd(math.sin(2.0 * math.pi * i / 4096.0) * (FS - 1)) for i in range(1025)]
print(arr("LT_SIN", "int32_t", sin_t))

# 5. tanh(i / 2048 * 4) * (FS - 1), i 0..2049 (2048 + 2 guard, as the host's TANH_T)
th_t = [rnd(math.tanh(i / 2048.0 * 4.0) * (FS - 1)) for i in range(2050)]
print(arr("LT_TANH", "int32_t", th_t))

# 6. BLEP residual table, M = 8: S(x) of the cardinal B-spline, Q24, 256 steps a sample (host lrry_voice.h blep_init)
def blep(M):
    fact = 1
    for i in range(2, M + 1):
        fact *= i
    t = []
    for i in range(M * 256 + 1):
        x = i / 256.0 - M / 2.0
        S = 0.0
        c = 1.0
        for k in range(M + 1):
            tt = x + M / 2.0 - k
            if tt > 0:
                S += (-1.0 if (k & 1) else 1.0) * c * (tt ** M)
            c = c * (M - k) / (k + 1)
        S /= fact
        t.append(rnd(S * 16777216.0))
    return t
print(arr("LT_BLEP8", "int32_t", blep(8)))
print(arr("LT_BLEP4", "int32_t", blep(4)))

# 7. 2^(j / 256), Q28, j 0..256 (octave fraction: detune, ratios)
p2_t = [rnd((2.0 ** (j / 256.0)) * Q28) for j in range(257)]
print(arr("LT_P2", "uint32_t", p2_t))

# 8. 1 / sqrt(n), n 0..7 (n 0: 0), Q28
isq_t = [0] + [rnd(Q28 / math.sqrt(n)) for n in range(1, 8)]
print(arr("LT_INVSQ", "int32_t", isq_t))
