"""L/RRY bench1 (PHASE60): writes the two suites for tools/bench_run.py (standard library only, over the USB serial console of a LRRY_BENCH build).

  python3 tools/gen_lrry_suite.py            writes tools/bench_suites/LRRY-POLY.txt and LRRY-COST.txt

LRRY-POLY: the 16 test patches (replaced 2026-11-02 by sounds of the 128, see PATCHES below; FULL STRESS is the 'all options on' patch, sent from the tool side), 1 .. 12 keys held 5 s, once on two cores (`tune core1 on`) and once
  on one core (`tune core1 off`). The bench1 build has no budget gate, no VOICE CAP and no shedding (LRRY_NOLIMIT), so every key sounds; the result's miss column, the
  two-core counters (c1late, tc*, tm*) and the recording's clicks say where it stops being clean.
LRRY-COST: the true cost of each feature: the base is TEST SAW (sent from the tool side on #03 SAW BASS), one feature switched on at a time (ids from PARAM_LIST.md: wide id = 128 + slot, X28 = 156), 1, 4 and
  8 keys on ONE core; cost per voice = the slope of avg over the keys, the fixed part = the intercept.
Run:  python3 tools/bench_run.py --onset --suite LRRY-POLY [--record]        (hands off the unit, MASTER down; results in bench_runs/<name>/)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bench_testpatch  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
# 2026-11-02: no test set in the unit's bank. The old test patches are replaced by the nearest sound of the 128 (SOUNDS_128.md numbers); TEST SAW and FULL STRESS
# are no sound of the 128: the suite loads #03 SAW BASS (TEST SAW) or #28 SUPER LEAD (FULL STRESS) and sends their values (tools/bench_testpatch.py). Row order and count as before (16).
PATCHES = [(3, "TEST SAW"), (60, "STRING MACH"), (4, "SQUELCH BASS"), (101, "TUBE BELL FM"), (29, "SYNC SCREAM"), (67, "HARP PLUCK"), (96, "STEREO KEYS"), (28, "FULL STRESS"),
           (48, "MOLTEN PAD"), (117, "RISER SAW"), (126, "WARP GATE"), (39, "DARK ORBIT"), (12, "FIFTHS UP"), (6, "WIDE BASS"), (89, "PULSE FUNK"), (52, "PAN FIELD")]
TOOL_SIDE = ("TEST SAW", "FULL STRESS")


def load_lines(num, name):
    """the suite lines that put the sound or tool-side test patch on part 1"""
    if name in TOOL_SIDE:
        return bench_testpatch.suite_lines(name)
    return [f'load patch 1 #{num:02d} "{name}"']
NOTES = ["C3", "E3", "G3", "B3", "D4", "F4", "A4", "C5", "E5", "G5", "B5", "D6"]
# feature: list of (id, value) on top of the base patch. OSC model enum: SAW 0 TRI 1 SINE 2 PULSE 3 SYNC 4 SUPER 5 FM 6 FOLD 7
FEATURES = [
    ("BASE", []),
    ("OSC2_SAW", [(168, 100)]),
    ("OSC1_SUPER", [(156, 5)]),
    ("OSC1_FM", [(156, 6)]),
    ("OSC1_FOLD", [(156, 7)]),
    ("OSC1_SYNC", [(156, 4)]),
    ("OSC1_PULSE", [(156, 3)]),
    ("OSC2_SUPER", [(165, 5), (168, 100)]),
    ("SUB", [(134, 100)]),
    ("NOISE", [(174, 80)]),
    ("RING", [(165, 0), (168, 100), (177, 100)]),
    ("MULTI12", [(45, 50), (47, 0), (48, 1)]),
    ("MULTI24", [(45, 50), (47, 0), (48, 2)]),
    ("TWIN_LP", [(45, 50), (47, 0), (48, 1), (43, 1), (106, 10)]),
    ("TWIN_LADDER", [(45, 50), (47, 0), (48, 1), (43, 5), (106, 10)]),
    ("TWIN_COMB", [(45, 50), (47, 0), (48, 1), (43, 6), (106, 10)]),
    ("DIRT_A_SOFT", [(182, 1), (26, 64)]),
    ("DIRT_A_FOLD", [(182, 3), (26, 64)]),
    ("DIRT_AB_PAR", [(182, 1), (26, 64), (185, 2), (186, 64), (189, 1)]),
    ("DIRT_AB_SER", [(182, 1), (26, 64), (185, 2), (186, 64), (189, 0)]),
]


def head(f, lines):
    f.append("\n".join(lines))
    f.append("")


def poly():
    out = ["# LRRY-POLY (generated by tools/gen_lrry_suite.py): the 16 test patches, 1 .. 12 keys, two cores then one core, no limit gate (bench1). 5 s each.",
           "# Read: miss / c1late / tc* columns of results.csv, the recording's clicks; the largest N with 0 misses over the whole run (--onset) and no clicks is the clean polyphony.",
           "suite LRRY-POLY", ""]
    for pi, (num, name) in enumerate(PATCHES, 1):
        for cores in ("2C", "1C"):
            for k in range(1, len(NOTES) + 1):
                out += [f"test P{pi:02d}_{cores}_N{k:02d}  #{num:02d} {name}, {'two cores' if cores == '2C' else 'one core'}, {k} keys",
                        *load_lines(num, name),
                        "tune core1 off" if cores == "1C" else "tune core1 on", "mods SENDS OFF",
                        "at 0.0  chord " + " ".join(NOTES[:k]) + " vel 100",
                        "at 5.0  release", "tail 1", "measure 1.0 5.0", "expect report", ""]
    open(os.path.join(HERE, "bench_suites", "LRRY-POLY.txt"), "w").write("\n".join(out) + "\n")
    print("LRRY-POLY:", 16 * 2 * len(NOTES), "tests")


def cost():
    out = ["# LRRY-COST (generated by tools/gen_lrry_suite.py): one feature at a time on TEST SAW (tool side), 1, 4 and 8 keys on ONE core. Per voice = slope of avg, fixed = intercept.",
           "suite LRRY-COST", ""]
    n = 0
    for fname, sets in FEATURES:
        for k in (1, 4, 8):
            out += [f"test C_{fname}_N{k}  {fname}, {k} keys, one core", *load_lines(3, "TEST SAW"), "tune core1 off", "mods SENDS OFF"]
            out += [f"set 1 {i} {v}" for i, v in sets]
            out += ["at 0.0  chord " + " ".join(NOTES[:k]) + " vel 100", "at 5.0  release", "tail 1", "measure 1.0 5.0", "expect report", ""]
            n += 1
    open(os.path.join(HERE, "bench_suites", "LRRY-COST.txt"), "w").write("\n".join(out) + "\n")
    print("LRRY-COST:", n, "tests")


def diag():
    out = ["# LRRY-DIAG (generated by tools/gen_lrry_suite.py): idle cost and TEST SAW (tool side) on two cores / one core, 0, 1, 2, 4, 6, 8, 10, 12 keys.", "suite LRRY-DIAG", ""]
    for cores in ("2C", "1C"):
        for k in (0, 1, 2, 4, 6, 8, 10, 12):
            out += [f"test D_{cores}_N{k:02d}  TEST SAW, {'two cores' if cores == '2C' else 'one core'}, {k} keys", *load_lines(3, "TEST SAW"),
                    "tune core1 off" if cores == "1C" else "tune core1 on", "mods SENDS OFF"]
            if k:
                out += ["at 0.0  chord " + " ".join(NOTES[:k]) + " vel 100", "at 5.0  release"]
            out += ["tail 1", "measure 1.0 5.0", "expect report", ""]
    open(os.path.join(HERE, "bench_suites", "LRRY-DIAG.txt"), "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    poly()
    cost()
    diag()
