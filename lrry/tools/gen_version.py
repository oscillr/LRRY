"""Write the version header from the single source of truth, the VERSION file at the L/RRY root.

  tools/gen_version.py build/gen/lrry_version.h

LRRY_VERSION      "0.2.1"
LRRY_VERSION_STR  "L/RRY 0.2.1 beta" (a 0.x.y version) or "L/RRY 1.0" (1.0 and later: no beta)   (what the device and the emulator page show)
L/RRY (4.8): a VERSION file "lrry-0.1.0-test1" gives LRRY_VERSION "0.1.0-test1", LRRY_VERSION_STR "L/RRY 0.1.0-test1" (no beta)
"""
import re
import sys
from pathlib import Path

vfile = Path(__file__).resolve().parents[2] / "VERSION"
ver = vfile.read_text().strip() if vfile.exists() else ""
lrry = re.fullmatch(r"lrry-(\d+\.\d+\.\d+-(?:test|bench)\d+)", ver)   # L/RRY 4.8: lrry-0.1.0-testN
if not lrry and not re.fullmatch(r"0\.\d+\.\d+|[1-9]\d*\.\d+|[1-9]\d*\.\d+\.\d+-(?:test|velocapture)\d+", ver):   # L/RRY 1.1: 1.1.0-testN
    sys.exit(f"gen_version: {vfile} must hold 0.MINOR.BUILD (e.g. 0.2.1), MAJOR.MINOR (1.0) or lrry-M.N.P-testN, found {ver!r}")
if lrry:
    ver, product, beta = lrry.group(1), "L/RRY", ""
else:
    product, beta = "L/RRY", (" beta" if ver.startswith("0.") else "")
Path(sys.argv[1]).write_text(
    "/* generated by tools/gen_version.py from the VERSION file; do not edit */\n"
    f'#define LRRY_VERSION "{ver}"\n#define LRRY_VERSION_STR "{product} {ver}{beta}"\n')
