/* ------------------------------------------------- L/RRY BENCH (bench builds only) --- */
/* MENU > SYSTEM > BENCH (LRRY_BENCH=1, docs/BENCH_GUIDE.md). Last in the unit and in sections of their own (the linker scripts put them after
 * everything else), so the normal build's data, its hot RAM block and the RAM ranges keep their places and every function its size (only the
 * code after the UI hooks moves a few bytes); a normal build has none of it */
#if LRRY_BENCH
/* every function, table and variable of the bench in a section of its own (clang 4 has no '#pragma clang section'): the linker scripts put them
 * after everything else, and a global with a section is never merged with the others (LLVM's GlobalMerge), so the normal code and data keep
 * their shape */
#define BENCH_FN __attribute__((section(".bench_text"), noinline))   /* (never inlined into the normal code: its functions keep their size) */
#define BENCH_RO __attribute__((section(".bench_rodata")))
#define BENCH_BSS __attribute__((section(".bench_bss")))
#include "bench.c"
#endif
